#include "libft.h"

char	*ft_strdup(const char *s1)
{
	char	*copy;
	int		strlen;
	int		i;

	strlen = 0;
	while (s1[strlen] != '\0')
		strlen++;
	copy = ft_calloc(sizeof(char), strlen + 1);
	if (copy == NULL)
		return (NULL);
	i = 0;
	while (s1[i] != '\0')
	{
		copy[i] = s1[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
